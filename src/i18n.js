export function normalizeLocale(locale) {
  return SUPPORTED_LOCALES.some((candidate) => candidate.id === locale) ? locale : DEFAULT_LOCALE;
}

export function t(locale, key, params = {}) {
  const normalized = normalizeLocale(locale);
  const template = UI_TEXT[normalized]?.[key] ?? UI_TEXT[DEFAULT_LOCALE][key] ?? key;
  return Object.entries(params).reduce(
    (text, [param, value]) => text.replaceAll(`{${param}}`, String(value)),
    template,
  );
}

export function translateCommon(locale, value) {
  return t(locale, value);
}

export function translateGameText(locale, value) {
  return presentGameText(value, { locale: normalizeLocale(locale) });
}

export function getLocalizedCategory(category, locale) {
  const normalized = normalizeLocale(locale);
  const translated = CATEGORY_TRANSLATIONS[category.id]?.[normalized];
  return translated ? { ...category, ...translated } : category;
}

function isTlidbLocaleSource(sourceUrl, locale) {
  try {
    const url = new URL(String(sourceUrl ?? ""));
    return (url.hostname === "tlidb.com" || url.hostname.endsWith(".tlidb.com"))
      && url.pathname.startsWith(`/${locale}/`);
  } catch {
    return false;
  }
}

export function getTlidbLocaleText(item, locale) {
  const normalized = normalizeLocale(locale);
  const localized = item?.tlidbText?.[normalized];
  return localized && isTlidbLocaleSource(localized.sourceUrl, normalized) ? localized : null;
}

function localizedItemField(item, localizedText, field, locale, { optional = false } = {}) {
  const status = localizedText?.sourceFieldStatus?.[field];
  const sourceValue = localizedText?.[field];
  if (status === "not-present") return "";
  if (status === "source-language-mixed" && containsHanScript(sourceValue)) {
    const sourceConflictText = locale === "ko"
      ? "한국어 원문 일부 미제공"
      : "Localized source partially unavailable";
    const supplement = locale === "ko"
      ? getCurrentKoreanGameTextSupplement(item, field)
      : null;
    if (supplement && !optional) {
      if (supplement.complete === true && supplement.presentation === "replace") {
        return presentGameText(supplement.text, { locale, optional });
      }
      const safeSource = presentGameText(sourceValue, { locale, optional: true }).trimEnd();
      const availableText = safeSource.includes(supplement.text)
        ? safeSource
        : [safeSource, supplement.text].filter(Boolean).join("\n");
      return `${availableText}\n${sourceConflictText}`;
    }
    return presentGameText(sourceValue, {
      locale,
      optional,
      unavailableText: sourceConflictText,
      partialUnavailableText: sourceConflictText,
    });
  }
  const localized = status === "exact" ? sourceValue : null;
  if (localized !== undefined && localized !== null && localized !== "") {
    return presentGameText(localized, { locale, optional });
  }
  if (optional) return "";
  return locale === "ko" ? "한국어 원문 미제공" : "Localized source unavailable";
}

export function getLocalizedItem(item, locale) {
  const normalized = normalizeLocale(locale);
  const localizedText = getTlidbLocaleText(item, normalized);
  const name = localizedItemField(item, localizedText, "name", normalized);
  const type = localizedItemField(item, localizedText, "type", normalized, { optional: true });
  const slot = localizedItemField(item, localizedText, "slot", normalized, { optional: true });
  const rarity = localizedItemField(item, localizedText, "rarity", normalized, { optional: true });
  const summary = localizedItemField(item, localizedText, "summary", normalized);
  const detail = localizedItemField(item, localizedText, "detail", normalized);
  const tags = localizedText?.sourceFieldStatus?.tags === "exact" && Array.isArray(localizedText.tags)
    ? localizedText.tags
      .map((tag) => presentGameText(tag, { locale: normalized, optional: true }))
      .filter(Boolean)
    : [];

  return {
    ...item,
    name,
    type,
    slot,
    rarity,
    tags,
    summary,
    detail,
    sourceName: item.name,
  };
}
